# 宽基/跨境（不归入主题，单独归类）
BROAD_KEYWORDS = ["沪深300", "中证500", "中证1000", "中证2000", "上证50", "上证指数", "创业板", "科创50",
                  "A50", "A500", "中证A股", "中证全指", "宽基", "300ETF", "500ETF", "1000ETF", "恒生", "港股",
                  "纳斯达克", "标普", "德国", "日经", "亚太", "全球"]


def classify_etf(name, benchmark=""):
    """返回主题名；宽基/跨境返回 '宽基'；未匹配返回 '其他'。"""
    full = str(name) + str(benchmark)
    for kw in BROAD_KEYWORDS:
        if kw in full:
            return "宽基"
    for theme, kws in THEME_KEYWORDS:
        for kw in kws:
            if kw in full:
                return theme
    return "其他"


def load_stock_etf():
    """加载股票型 ETF（剔除跨境/商品/债券）。"""
    import pandas as pd
    from config import ETF_BASIC_CSV
    b = pd.read_csv(ETF_BASIC_CSV)
    b = b[b["fund_type"] == "股票型"].copy()
    b["theme"] = b.apply(lambda r: classify_etf(r["name"], r.get("benchmark", "")), axis=1)
    return b


