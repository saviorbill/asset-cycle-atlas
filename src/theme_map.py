# 反查：行业 → 主题
INDUSTRY_TO_THEME = {}
for theme, inds in THEME_MAP.items():
    for ind in inds:
        INDUSTRY_TO_THEME[ind] = theme

THEMES = list(THEME_MAP.keys())


def industry_to_theme(ind):
    return INDUSTRY_TO_THEME.get(ind, "其他")


