# -*- coding: utf-8 -*-
"""给台账里的每条建议算「到期结果」，并汇总成检验指标。

只读台账，不改台账。每条建议按 asof 收盘后生成，从**下一个交易日**起算：
    T+1 收盘买入 → T+1+h 收盘卖出（保守、完全可执行）
未到期（数据不够 h 个交易日）的标 pending，不参与统计。

输出：应用数据/validation/scored.csv、web/validation.js

指标定义：
  方向命中  买入类建议：未来 20 日收益 > 0；等待类建议：未来 20 日收益 <= 0
  超额      推荐指数未来 20 日收益 − 8 个指数等权的未来 20 日收益
  区间覆盖  实际 60 日收益是否落在当时给出的 p10–p90
  Brier     模型上行概率与"实际上涨"的均方误差（越低越好，0.25 相当于瞎猜）
"""
import json
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from config import DATA_DIR, INDEX_CSV  # noqa: E402

VAL = os.path.join(DATA_DIR, "validation")
REC = os.path.join(VAL, "recommendations.csv")
OUT_CSV = os.path.join(VAL, "scored.csv")
OUT_JS = os.path.join(ROOT, "web", "validation.js")
HORIZONS = [5, 20, 60]
IDX = ["上证指数", "深证成指", "沪深300", "中证500",
       "中证1000", "中证2000", "创业板指", "科创50"]
BUY = {"可分批买入", "可小仓位试探"}


def fwd_return(px, name, asof, h):
    """T+1 收盘买入，T+1+h 收盘卖出。"""
    s = px[name].dropna()
    pos = s.index.searchsorted(pd.Timestamp(asof), side="right")
    i0, i1 = pos, pos + h
    if i1 >= len(s):
        return None
    return float(s.iloc[i1] / s.iloc[i0] - 1)


def main():
    if not os.path.exists(REC):
        print("台账不存在，先跑 log_recommendation.py")
        return
    df = pd.read_csv(REC, dtype={"asof": str})
    px = pd.read_csv(INDEX_CSV, parse_dates=["date"]).set_index("date").sort_index()
    for c in IDX:
        if c in px.columns:
            px[c] = px[c].replace(0.0, np.nan)

    rows = []
    for r in df.to_dict("records"):
        rec = dict(r)
        name = r.get("index_name")
        for h in HORIZONS:
            ret = fwd_return(px, name, r["asof"], h) if name in px.columns else None
            rec["ret%d" % h] = None if ret is None else round(ret * 100, 2)
            rec["bench%d" % h] = None
            if ret is not None:
                brs = [fwd_return(px, n, r["asof"], h) for n in IDX if n in px.columns]
                brs = [x for x in brs if x is not None]
                if brs:
                    rec["bench%d" % h] = round(float(np.mean(brs)) * 100, 2)
            rec["excess%d" % h] = (None if rec["ret%d" % h] is None or rec["bench%d" % h] is None
                                   else round(rec["ret%d" % h] - rec["bench%d" % h], 2))
        # 方向与校准（以 20 日为主）
        r20 = rec.get("ret20")
        if r20 is None:
            rec["hit20"] = None
        else:
            is_buy = str(r.get("stance")) in BUY
            rec["hit20"] = int((r20 > 0) if is_buy else (r20 <= 0))
        r60 = rec.get("ret60")
        pup = r.get("ml_pup")
        rec["brier60"] = (None if r60 is None or pd.isna(pup)
                          else round(((float(pup) / 100) - (1 if r60 > 0 else 0)) ** 2, 4))
        in_band = None
        if r60 is not None and not pd.isna(r.get("ml_p10")) and not pd.isna(r.get("ml_p90")):
            in_band = int(float(r["ml_p10"]) <= r60 <= float(r["ml_p90"]))
        rec["cover60"] = in_band
        rows.append(rec)

    out = pd.DataFrame(rows)
    out.to_csv(OUT_CSV, index=False, encoding="utf-8-sig")

    def _mean(col, h=None):
        v = pd.to_numeric(out[col], errors="coerce").dropna()
        return None if not len(v) else float(v.mean())

    summary = dict(
        n_total=int(len(out)),
        n_hit=int(pd.to_numeric(out["hit20"], errors="coerce").notna().sum()),
        n_cover=int(pd.to_numeric(out["cover60"], errors="coerce").notna().sum()),
        hit20=_mean("hit20"), excess20=_mean("excess20"), excess60=_mean("excess60"),
        cover60=_mean("cover60"), brier60=_mean("brier60"),
        first=str(out["asof"].iloc[0]), last=str(out["asof"].iloc[-1]),
    )
    recent = []
    for r in out.tail(12).to_dict("records"):
        recent.append(dict(asof=str(r["asof"]), stance=r.get("stance"),
                           index=str(r.get("index_name")),
                           ret20=r.get("ret20"), ret60=r.get("ret60"),
                           hit20=r.get("hit20")))
    payload = dict(summary=summary, recent=recent)
    with open(OUT_JS, "w", encoding="utf-8") as f:
        f.write("/* generated by src/score_recommendations.py — do not edit */\n")
        f.write("window.WAW=window.WAW||{};window.WAW.validation=")
        f.write(json.dumps(payload, ensure_ascii=False, separators=(",", ":")))
        f.write(";\n")

    print("台账 %d 条（%s ~ %s）" % (summary["n_total"], summary["first"], summary["last"]))
    if summary["n_hit"]:
        print("  方向命中（20日） %.0f%%  n=%d" % (summary["hit20"] * 100, summary["n_hit"]))
        print("  超额（20日）     %+.2f%%" % summary["excess20"])
    else:
        print("  尚无到期的 20 日样本，继续记录")
    if summary["n_cover"]:
        print("  60日区间覆盖     %.0f%%（目标 80%%）  n=%d" %
              (summary["cover60"] * 100, summary["n_cover"]))
        print("  Brier            %.3f（0.25 = 瞎猜）" % summary["brier60"])
    else:
        print("  尚无到期的 60 日样本")
    print("→ %s" % OUT_JS)


if __name__ == "__main__":
    main()
